/// 建立数据库连接并初始化表
fn open_db() -> Result<Connection, String> {
    let db_path = usage_db_path();
    if let Some(parent) = db_path.parent() {
        fs::create_dir_all(parent).map_err(|e| format!("Failed to create db dir: {}", e))?;
    }
    let conn = Connection::open(&db_path).map_err(|e| format!("Failed to open usage db: {}", e))?;
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS usage_events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            skill_id TEXT NOT NULL,
            tool_id TEXT NOT NULL,
            event_type TEXT NOT NULL,
            ts INTEGER NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_usage_skill ON usage_events(skill_id);
        CREATE INDEX IF NOT EXISTS idx_usage_tool ON usage_events(tool_id);
        CREATE INDEX IF NOT EXISTS idx_usage_ts ON usage_events(ts);",
    )
    .map_err(|e| format!("Failed to init usage table: {}", e))?;

    ensure_usage_column(&conn, "session_id", "TEXT")?;
    ensure_usage_column(&conn, "turn_id", "TEXT")?;
    ensure_usage_column(&conn, "source", "TEXT")?;
    ensure_usage_column(&conn, "dedupe_key", "TEXT")?;
    conn.execute_batch(
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_usage_dedupe
         ON usage_events(dedupe_key)
         WHERE dedupe_key IS NOT NULL;",
    )
    .map_err(|e| format!("Failed to init usage dedupe index: {}", e))?;
    Ok(conn)
}

fn ensure_usage_column(conn: &Connection, name: &str, column_type: &str) -> Result<(), String> {
    let mut stmt = conn
        .prepare("PRAGMA table_info(usage_events)")
        .map_err(|e| format!("Failed to inspect usage table: {}", e))?;
    let columns = stmt
        .query_map([], |row| row.get::<_, String>(1))
        .map_err(|e| format!("Failed to query usage columns: {}", e))?;
    if columns.flatten().any(|column| column == name) {
        return Ok(());
    }
    conn.execute(
        &format!(
            "ALTER TABLE usage_events ADD COLUMN {} {}",
            name, column_type
        ),
        [],
    )
    .map_err(|e| format!("Failed to add usage column {}: {}", name, e))?;
    Ok(())
}

#[derive(Debug)]
struct ExtractedUsage {
    skill_ids: Vec<String>,
    session_id: Option<String>,
    turn_id: Option<String>,
    event_type: String,
    source: &'static str,
}

/// Extract skill identifiers and turn metadata from a hook event.
fn extract_usage(event: &UsageEvent) -> Option<ExtractedUsage> {
    let raw = event.raw.as_ref()?;
    let raw_value: serde_json::Value = serde_json::from_str(raw).ok()?;
    let hook_event = raw_value.get("hook_event_name").and_then(|v| v.as_str())?;
    let session_id = raw_value
        .get("session_id")
        .and_then(|v| v.as_str())
        .map(str::to_string);
    let turn_id = raw_value
        .get("turn_id")
        .and_then(|v| v.as_str())
        .map(str::to_string);

    let (skill_ids, source) = match hook_event {
        "PostToolUse" => {
            let tool_input = raw_value.get("tool_input")?;
            let ids = if event.tool_id == "codex" {
                // Codex does not expose a Skill tool. Generic MCP inputs may
                // contain fields such as `name`, so only count actual SKILL.md
                // paths for Codex instead of interpreting arbitrary fields.
                extract_skill_ids_from_skill_paths(tool_input)
            } else {
                extract_skill_ids_from_value(tool_input)
            };
            (ids, "post_tool_use")
        }
        "UserPromptSubmit" => {
            let prompt = raw_value.get("prompt").and_then(|v| v.as_str())?;
            if event.tool_id == "codex" {
                (extract_codex_skill_mentions(prompt), "explicit_prompt")
            } else {
                (
                    extract_skill_from_slash_command(prompt)
                        .into_iter()
                        .collect(),
                    "explicit_prompt",
                )
            }
        }
        "Stop" if event.tool_id == "codex" => {
            let transcript_path = raw_value.get("transcript_path").and_then(|v| v.as_str())?;
            (
                extract_skill_ids_from_transcript(Path::new(transcript_path)),
                "transcript_fallback",
            )
        }
        _ => return None,
    };

    if skill_ids.is_empty() {
        return None;
    }

    Some(ExtractedUsage {
        skill_ids,
        session_id,
        turn_id,
        event_type: hook_event.to_string(),
        source,
    })
}

fn extract_skill_from_slash_command(prompt: &str) -> Option<String> {
    let trimmed = prompt.trim();
    if !trimmed.starts_with('/') {
        return None;
    }
    let after_slash = &trimmed[1..];
    let end = after_slash
        .find(|c: char| !c.is_alphanumeric() && c != '-' && c != '_')
        .unwrap_or(after_slash.len());
    if end == 0 {
        return None;
    }
    let skill_name = &after_slash[..end];
    if skill_name.is_empty() {
        return None;
    }
    let builtins = [
        "help",
        "clear",
        "compact",
        "config",
        "cost",
        "doctor",
        "exit",
        "init",
        "login",
        "logout",
        "memory",
        "model",
        "permissions",
        "review",
        "status",
        "terminal-setup",
        "vim",
        "bug",
        "resume",
        "release-notes",
        "feedback",
        "mcp",
        "usage",
    ];
    if builtins.contains(&skill_name) {
        return None;
    }
    Some(skill_name.to_string())
}

/// Codex officially uses `$skill-name`; `@skill-name` is also accepted here
/// for compatibility with composer surfaces that render mentions that way.
fn extract_codex_skill_mentions(prompt: &str) -> Vec<String> {
    let env_vars = [
        "HOME",
        "PATH",
        "USER",
        "SHELL",
        "TMPDIR",
        "LANG",
        "LC_ALL",
        "PWD",
        "OLDPWD",
        "TERM",
        "EDITOR",
        "VISUAL",
        "GOPATH",
        "GOROOT",
        "JAVA_HOME",
        "NODE_PATH",
        "PYTHONPATH",
        "RUSTUP_HOME",
        "CARGO_HOME",
    ];
    let mut result = Vec::new();
    let bytes = prompt.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'$' || bytes[i] == b'@' {
            // Mention must be at start or preceded by whitespace.
            if i > 0 {
                let prev = bytes[i - 1];
                if prev != b' ' && prev != b'\t' && prev != b'\n' && prev != b'\r' {
                    i += 1;
                    continue;
                }
            }
            // Extract name after $. Skill names must start with a letter
            // to avoid matching prices like $100.
            let rest = &prompt[i + 1..];
            let first = rest.chars().next();
            if first.is_none() || !first.unwrap().is_ascii_alphabetic() {
                i += 1;
                continue;
            }
            let end = rest
                .find(|c: char| !c.is_alphanumeric() && c != '-' && c != '_' && c != ':')
                .unwrap_or(rest.len());
            if end > 0 {
                let mention = &rest[..end];
                let name = mention.rsplit(':').next().unwrap_or(mention);
                if !env_vars.contains(&name) && !name.is_empty() {
                    result.push(name.to_string());
                }
            }
        }
        i += 1;
    }
    dedupe_skill_ids(result)
}

fn extract_skill_ids_from_value(tool_input: &serde_json::Value) -> Vec<String> {
    let mut result = Vec::new();
    if let Some(obj) = tool_input.as_object() {
        // "command" is used by WorkBuddy's Skill tool; others use skill_id/skill_name/name/skill
        for key in ["skill_id", "skill_name", "name", "skill", "command"] {
            if let Some(val) = obj.get(key) {
                if let Some(s) = val.as_str() {
                    if !s.is_empty() {
                        result.push(s.to_string());
                    }
                }
            }
        }
    }
    dedupe_skill_ids(result)
}

fn dedupe_skill_ids(ids: Vec<String>) -> Vec<String> {
    let mut seen = HashSet::new();
    ids.into_iter()
        .filter(|id| !id.is_empty() && seen.insert(id.clone()))
        .collect()
}

fn collect_string_values(value: &serde_json::Value, output: &mut Vec<String>) {
    match value {
        serde_json::Value::String(s) => output.push(s.clone()),
        serde_json::Value::Array(items) => {
            for item in items {
                collect_string_values(item, output);
            }
        }
        serde_json::Value::Object(obj) => {
            for value in obj.values() {
                collect_string_values(value, output);
            }
        }
        _ => {}
    }
}

fn extract_skill_ids_from_skill_paths(value: &serde_json::Value) -> Vec<String> {
    let mut strings = Vec::new();
    collect_string_values(value, &mut strings);
    dedupe_skill_ids(
        strings
            .iter()
            .flat_map(|value| extract_skill_ids_from_text(value))
            .collect(),
    )
}

fn extract_skill_ids_from_text(text: &str) -> Vec<String> {
    let normalized = text.replace('\\', "/");
    let lowercase = normalized.to_ascii_lowercase();
    let needle = "skill.md";
    let mut result = Vec::new();
    let mut search_from = 0;

    while let Some(relative) = lowercase[search_from..].find(needle) {
        let end = search_from + relative + needle.len();
        let mut start = search_from + relative;
        while start > 0 {
            let ch = normalized.as_bytes()[start - 1];
            if ch.is_ascii_whitespace()
                || matches!(
                    ch,
                    b'\''
                        | b'"'
                        | b'`'
                        | b'='
                        | b'('
                        | b')'
                        | b'['
                        | b']'
                        | b'{'
                        | b'}'
                        | b','
                        | b';'
                        | b'|'
                )
            {
                break;
            }
            start -= 1;
        }

        let candidate =
            normalized[start..end].trim_matches(|c: char| c == '\'' || c == '"' || c == '`');
        if let Some((parent, _)) = candidate.rsplit_once('/') {
            if let Some(skill_id) = parent.rsplit('/').next() {
                if !skill_id.is_empty() && skill_id != "." && skill_id != ".." {
                    result.push(skill_id.to_string());
                }
            }
        }
        search_from = end;
    }

    dedupe_skill_ids(result)
}

fn is_user_message_record(value: &serde_json::Value) -> bool {
    let payload = value.get("payload").unwrap_or(value);
    payload.get("type").and_then(|v| v.as_str()) == Some("message")
        && payload.get("role").and_then(|v| v.as_str()) == Some("user")
}

fn is_tool_call_record(value: &serde_json::Value) -> bool {
    fn contains_tool_call(value: &serde_json::Value) -> bool {
        match value {
            serde_json::Value::Object(obj) => {
                if obj
                    .get("type")
                    .and_then(|v| v.as_str())
                    .map(|kind| {
                        kind == "function_call" || kind == "custom_tool_call" || kind == "tool_call"
                    })
                    .unwrap_or(false)
                {
                    return true;
                }
                obj.values().any(contains_tool_call)
            }
            serde_json::Value::Array(items) => items.iter().any(contains_tool_call),
            _ => false,
        }
    }
    contains_tool_call(value)
}

fn extract_skill_ids_from_transcript(path: &Path) -> Vec<String> {
    let mut file = match fs::File::open(path) {
        Ok(file) => file,
        Err(_) => return Vec::new(),
    };
    let len = file.metadata().map(|meta| meta.len()).unwrap_or(0);
    let start = len.saturating_sub(TRANSCRIPT_TAIL_BYTES);
    if file.seek(SeekFrom::Start(start)).is_err() {
        return Vec::new();
    }
    let mut content = String::new();
    if file.read_to_string(&mut content).is_err() {
        return Vec::new();
    }
    if start > 0 {
        if let Some(first_newline) = content.find('\n') {
            content = content[first_newline + 1..].to_string();
        }
    }

    let records: Vec<serde_json::Value> = content
        .lines()
        .filter_map(|line| serde_json::from_str(line).ok())
        .collect();
    let turn_start = records
        .iter()
        .rposition(is_user_message_record)
        .map(|index| index + 1)
        .unwrap_or(0);

    let mut ids = Vec::new();
    for record in records.iter().skip(turn_start) {
        if is_tool_call_record(record) {
            ids.extend(extract_skill_ids_from_skill_paths(record));
        }
    }
    dedupe_skill_ids(ids)
}

/// 解析一个 pending 文件并写入 SQLite
fn import_pending_file(conn: &Connection, file_path: &PathBuf) -> Result<usize, String> {
    let content =
        fs::read_to_string(file_path).map_err(|e| format!("Failed to read pending file: {}", e))?;
    let trimmed = content.trim();
    if trimmed.is_empty() {
        return Ok(0);
    }
    let event: UsageEvent = match serde_json::from_str(trimmed) {
        Ok(e) => e,
        Err(_) => return Ok(0),
    };
    let usage = match extract_usage(&event) {
        Some(usage) => usage,
        None => return Ok(0),
    };
    let mut inserted = 0;
    for skill_id in usage.skill_ids {
        let dedupe_key = match (&usage.session_id, &usage.turn_id) {
            (Some(session_id), Some(turn_id)) => Some(format!(
                "{}:{}:{}:{}",
                event.tool_id, session_id, turn_id, skill_id
            )),
            _ => None,
        };
        inserted += conn
            .execute(
                "INSERT OR IGNORE INTO usage_events
                 (skill_id, tool_id, event_type, ts, session_id, turn_id, source, dedupe_key)
                 VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8)",
                rusqlite::params![
                    skill_id,
                    &event.tool_id,
                    &usage.event_type,
                    event.ts,
                    usage.session_id.as_deref(),
                    usage.turn_id.as_deref(),
                    usage.source,
                    dedupe_key,
                ],
            )
            .map_err(|e| format!("Failed to insert usage event: {}", e))?;
    }
    Ok(inserted)
}

/// 扫描 pending 目录，导入所有文件到 SQLite，导入后删除
pub fn import_pending_events(conn: &Connection) -> Result<usize, String> {
    let dir = pending_dir();
    if !dir.exists() {
        return Ok(0);
    }
    let entries = fs::read_dir(&dir).map_err(|e| format!("Failed to read pending dir: {}", e))?;
    let mut count = 0;
    for entry in entries.flatten() {
        let path = entry.path();
        // 只处理 .json 文件，跳过 .tmp- 前缀的临时文件
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
        if !name.ends_with(".json") || name.starts_with(".tmp-") {
            continue;
        }
        match import_pending_file(conn, &path) {
            Ok(imported) => {
                count += imported;
                let _ = fs::remove_file(&path);
            }
            Err(_) => {
                // 导入出错，保留文件等待下次重试
            }
        }
    }
    Ok(count)
}

/// 迁移旧 logl 文件到 SQLite（一次性）
fn migrate_legacy_log(conn: &Connection) -> Result<usize, String> {
    let log_path = skills_manager_dir().join(LEGACY_LOG_FILE);
    if !log_path.exists() {
        return Ok(0);
    }
    let content =
        fs::read_to_string(&log_path).map_err(|e| format!("Failed to read legacy log: {}", e))?;
    let mut count = 0;
    for line in content.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let event: UsageEvent = match serde_json::from_str(line) {
            Ok(e) => e,
            Err(_) => continue,
        };
        let usage = match extract_usage(&event) {
            Some(usage) => usage,
            None => continue,
        };
        for skill_id in usage.skill_ids {
            let _ = conn.execute(
                "INSERT INTO usage_events
                 (skill_id, tool_id, event_type, ts, session_id, turn_id, source)
                 VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)",
                rusqlite::params![
                    skill_id,
                    &event.tool_id,
                    &usage.event_type,
                    event.ts,
                    usage.session_id.as_deref(),
                    usage.turn_id.as_deref(),
                    usage.source,
                ],
            );
            count += 1;
        }
    }
    // 迁移成功后删除旧 logl
    let _ = fs::remove_file(&log_path);
    Ok(count)
}

#[tauri::command]
pub fn get_skill_usage_stats() -> Result<HashMap<String, SkillUsageStats>, String> {
    let conn = open_db()?;
    // 先导入 pending 文件
    let _ = import_pending_events(&conn);

    let mut stmt = conn
        .prepare("SELECT skill_id, tool_id, COUNT(*) as cnt, MAX(ts) as last_ts FROM usage_events GROUP BY skill_id, tool_id")
        .map_err(|e| format!("Failed to prepare query: {}", e))?;

    let mut stats: HashMap<String, SkillUsageStats> = HashMap::new();
    let rows = stmt
        .query_map([], |row| {
            Ok((
                row.get::<_, String>(0)?,
                row.get::<_, String>(1)?,
                row.get::<_, u64>(2)?,
                row.get::<_, Option<i64>>(3)?,
            ))
        })
        .map_err(|e| format!("Failed to query usage: {}", e))?;

    for row in rows.flatten() {
        let (skill_id, tool_id, cnt, last_ts) = row;
        let entry = stats.entry(skill_id).or_default();
        entry.total += cnt;
        entry.by_tool.insert(tool_id, cnt);
        if let Some(ts) = last_ts {
            if ts > entry.last_called_at.unwrap_or(0) {
                entry.last_called_at = Some(ts);
            }
        }
    }
    Ok(stats)
}

#[tauri::command]
pub fn clear_usage_stats() -> Result<(), String> {
    let conn = open_db()?;
    conn.execute("DELETE FROM usage_events", [])
        .map_err(|e| format!("Failed to clear usage events: {}", e))?;
    // 清空 pending 目录
    let dir = pending_dir();
    if dir.exists() {
        if let Ok(entries) = fs::read_dir(&dir) {
            for entry in entries.flatten() {
                let _ = fs::remove_file(entry.path());
            }
        }
    }
    Ok(())
}

