/// 生成 hook 命令字符串
fn build_hook_command() -> String {
    let script_path = hook_script_path();
    if cfg!(target_os = "windows") {
        // Windows: PowerShell
        format!(
            "powershell -ExecutionPolicy Bypass -File \"{}\"",
            script_path.to_string_lossy()
        )
    } else {
        // Unix: bash
        format!("bash \"{}\"", script_path.to_string_lossy())
    }
}

fn find_sm_hook_entry_in(settings: &serde_json::Value, event_key: &str) -> Option<usize> {
    let hooks = settings.get("hooks")?;
    let event_arr = hooks.get(event_key)?;
    let arr = event_arr.as_array()?;
    for (i, entry) in arr.iter().enumerate() {
        if event_key == "PostToolUse" {
            let matcher = entry.get("matcher").and_then(|m| m.as_str()).unwrap_or("");
            if matcher != "Skill" {
                continue;
            }
        }
        let hook_list = entry.get("hooks").and_then(|h| h.as_array());
        if let Some(hooks) = hook_list {
            for h in hooks {
                let cmd = h.get("command").and_then(|c| c.as_str()).unwrap_or("");
                if cmd.contains(HOOK_MARKER)
                    || cmd.contains("claude-skill-usage.sh")
                    || cmd.contains("claude-skill-usage.ps1")
                {
                    return Some(i);
                }
            }
        }
    }
    None
}

fn is_hook_installed() -> bool {
    let settings_path = claude_settings_path();
    let content = match fs::read_to_string(&settings_path) {
        Ok(c) => c,
        Err(_) => return false,
    };
    let settings: serde_json::Value = match serde_json::from_str(&content) {
        Ok(v) => v,
        Err(_) => return false,
    };
    find_sm_hook_entry_in(&settings, "PostToolUse").is_some()
        || find_sm_hook_entry_in(&settings, "UserPromptSubmit").is_some()
}

#[tauri::command]
pub fn install_usage_hook() -> Result<(), String> {
    // 1. Write hook script
    let hook_dir = skills_manager_dir().join(HOOK_DIR);
    fs::create_dir_all(&hook_dir).map_err(|e| format!("Failed to create hook dir: {}", e))?;
    let script_path = hook_script_path();
    fs::write(&script_path, hook_script_content())
        .map_err(|e| format!("Failed to write hook script: {}", e))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let perms = fs::Permissions::from_mode(0o755);
        fs::set_permissions(&script_path, perms)
            .map_err(|e| format!("Failed to set hook script permissions: {}", e))?;
    }

    // 2. Create pending directory
    fs::create_dir_all(pending_dir())
        .map_err(|e| format!("Failed to create pending dir: {}", e))?;

    // 3. Inject into Claude Code settings.json
    let settings_path = claude_settings_path();
    if let Some(parent) = settings_path.parent() {
        fs::create_dir_all(parent).map_err(|e| format!("Failed to create .claude dir: {}", e))?;
    }

    let content = fs::read_to_string(&settings_path).unwrap_or_else(|_| "{}".to_string());
    let mut settings: serde_json::Value = serde_json::from_str(&content)
        .map_err(|e| format!("Failed to parse Claude settings.json: {}", e))?;

    let hook_command = build_hook_command();

    if settings.get("hooks").is_none() {
        settings["hooks"] = serde_json::json!({});
    }

    // PostToolUse: matcher "Skill"
    remove_sm_entries(&mut settings, "PostToolUse");
    if settings["hooks"].get("PostToolUse").is_none() {
        settings["hooks"]["PostToolUse"] = serde_json::json!([]);
    }
    let post_entry = serde_json::json!({
        "matcher": "Skill",
        "hooks": [{
            "type": "command",
            "command": hook_command
        }]
    });
    settings["hooks"]["PostToolUse"]
        .as_array_mut()
        .expect("PostToolUse should be array")
        .push(post_entry);

    // UserPromptSubmit: no matcher
    remove_sm_entries(&mut settings, "UserPromptSubmit");
    if settings["hooks"].get("UserPromptSubmit").is_none() {
        settings["hooks"]["UserPromptSubmit"] = serde_json::json!([]);
    }
    let submit_entry = serde_json::json!({
        "hooks": [{
            "type": "command",
            "command": hook_command
        }]
    });
    settings["hooks"]["UserPromptSubmit"]
        .as_array_mut()
        .expect("UserPromptSubmit should be array")
        .push(submit_entry);

    let output = serde_json::to_string_pretty(&settings)
        .map_err(|e| format!("Failed to serialize settings: {}", e))?;
    fs::write(&settings_path, output)
        .map_err(|e| format!("Failed to write Claude settings.json: {}", e))?;

    // Install Codex hooks as part of the same feature so failures are visible.
    install_codex_usage_hook_internal()?;
    install_workbuddy_usage_hook_internal()?;

    Ok(())
}

fn remove_sm_entries(settings: &mut serde_json::Value, event_key: &str) {
    while let Some(idx) = find_sm_hook_entry_in(settings, event_key) {
        if let Some(arr) = settings
            .get_mut("hooks")
            .and_then(|h| h.get_mut(event_key))
            .and_then(|p| p.as_array_mut())
        {
            arr.remove(idx);
        } else {
            break;
        }
    }
}

#[tauri::command]
pub fn uninstall_usage_hook() -> Result<(), String> {
    let settings_path = claude_settings_path();
    let content = fs::read_to_string(&settings_path).unwrap_or_else(|_| "{}".to_string());
    let mut settings: serde_json::Value = serde_json::from_str(&content)
        .map_err(|e| format!("Failed to parse Claude settings.json: {}", e))?;

    remove_sm_entries(&mut settings, "PostToolUse");
    remove_sm_entries(&mut settings, "UserPromptSubmit");

    let output = serde_json::to_string_pretty(&settings)
        .map_err(|e| format!("Failed to serialize settings: {}", e))?;
    fs::write(&settings_path, output)
        .map_err(|e| format!("Failed to write Claude settings.json: {}", e))?;

    uninstall_codex_usage_hook_internal()?;
    uninstall_workbuddy_usage_hook_internal()?;

    Ok(())
}

