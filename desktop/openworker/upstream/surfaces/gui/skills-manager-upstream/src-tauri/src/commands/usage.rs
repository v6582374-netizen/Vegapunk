    fn workbuddy_uninstall_removes_plugin_files_and_registrations() {
        with_temp_home(|home| {
            install_workbuddy_usage_hook_internal().expect("install should succeed");
            assert!(is_workbuddy_hook_installed());

            uninstall_workbuddy_usage_hook_internal().expect("uninstall should succeed");

            // 插件目录应被删除
            let plugin_root = home.join(".skills-manager").join("hooks").join("workbuddy-plugin");
            assert!(!plugin_root.exists(), "plugin dir should be removed");

            // known_marketplaces.json 应不再含 skills-manager-local
            let mp_path = home
                .join(".workbuddy")
                .join("plugins")
                .join("known_marketplaces.json");
            let mp: serde_json::Value =
                serde_json::from_str(&fs::read_to_string(&mp_path).unwrap()).unwrap();
            assert!(mp.get(WORKBUDDY_MARKETPLACE_ID).is_none());

            // settings.json 的 enabledPlugins 应不再含插件
            let settings_path = home.join(".workbuddy").join("settings.json");
            let settings: serde_json::Value =
                serde_json::from_str(&fs::read_to_string(&settings_path).unwrap()).unwrap();
            assert!(settings
                .get("enabledPlugins")
                .and_then(|p| p.get(workbuddy_plugin_enabled_key()))
                .is_none());

            assert!(!is_workbuddy_hook_installed());
        });
    }

