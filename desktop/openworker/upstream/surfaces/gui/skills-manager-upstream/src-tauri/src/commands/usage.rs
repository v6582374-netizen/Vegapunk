fn add_codex_hook_entries(settings: &mut serde_json::Value, hook_command: &str) {
    if settings.get("hooks").is_none() {
        settings["hooks"] = serde_json::json!({});
    }

    for event_key in ["UserPromptSubmit", "PostToolUse", "Stop"] {
        remove_codex_sm_entries(settings, event_key);
        if settings["hooks"].get(event_key).is_none() {
            settings["hooks"][event_key] = serde_json::json!([]);
        }
    }

    settings["hooks"]["UserPromptSubmit"]
        .as_array_mut()
        .expect("UserPromptSubmit should be array")
        .push(serde_json::json!({
            "hooks": [{"type": "command", "command": hook_command}]
        }));

    // Bash catches normal SKILL.md reads. MCP matchers cover filesystem tools.
    settings["hooks"]["PostToolUse"]
        .as_array_mut()
        .expect("PostToolUse should be array")
        .push(serde_json::json!({
            "matcher": "^(Bash|mcp__.*)$",
            "hooks": [{"type": "command", "command": hook_command}]
        }));

    // Stop provides transcript_path and compensates for unified_exec calls that
    // PostToolUse does not expose yet.
    settings["hooks"]["Stop"]
        .as_array_mut()
        .expect("Stop should be array")
        .push(serde_json::json!({
            "hooks": [{"type": "command", "command": hook_command}]
        }));
}

