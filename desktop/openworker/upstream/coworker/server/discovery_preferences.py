"""Validated global defaults for Discovery Launch execution.

The settings surface deliberately owns only the parameters that are part of the
Discovery workflow contract.  It does not mirror the complete YAML configuration
tree: paths, memory stores, providers' transport details, resource allocation, and
other implementation details stay outside this module.

The module is intentionally deep at its seam.  Callers only need ``get``, ``save``,
and ``snapshot``; type/range/enum validation, complete-shape checks, and durable
atomic replacement are kept here so every caller observes the same contract.
"""

from __future__ import annotations

