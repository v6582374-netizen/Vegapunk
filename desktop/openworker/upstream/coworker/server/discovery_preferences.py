_EXPECTED_SHAPE = DEFAULT_DISCOVERY_LAUNCH_PREFERENCES


def _path_value(values: Mapping[str, Any], path: str) -> Any:
    current: Any = values
    for part in path.split("."):
        if not isinstance(current, Mapping) or part not in current:
            raise KeyError(path)
        current = current[part]
    return current


def _violation(path: str, message: str) -> dict[str, str]:
    return {"path": path, "message": message}


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _validate_shape_and_values(values: Any) -> dict[str, Any]:
    violations: list[dict[str, Any]] = []

    if not isinstance(values, dict):
        raise DiscoveryPreferencesValidationError(
            "Discovery Launch preferences must be an object",
            [_violation("", "an object is required")],
        )

    def walk_shape(candidate: Any, expected: Any, path: str) -> Any:
        if isinstance(expected, dict):
            if not isinstance(candidate, dict):
                violations.append(_violation(path, "an object is required"))
                return None
            expected_keys = set(expected)
            actual_keys = set(candidate)
            for unknown in sorted(actual_keys - expected_keys):
                unknown_path = f"{path}.{unknown}" if path else unknown
                violations.append(_violation(unknown_path, "unknown parameter"))
            for missing in sorted(expected_keys - actual_keys):
                missing_path = f"{path}.{missing}" if path else missing
                violations.append(_violation(missing_path, "parameter is required"))
            return {
                key: walk_shape(candidate[key], expected[key], f"{path}.{key}" if path else key)
                for key in sorted(actual_keys & expected_keys)
            }
        return candidate

    normalized = walk_shape(values, _EXPECTED_SHAPE, "")
    if violations:
        raise DiscoveryPreferencesValidationError(
            "Discovery Launch preferences contain unknown or missing parameters",
            violations,
        )

    for path, definition in _PARAMETER_DEFINITIONS.items():
        try:
            value = _path_value(values, path)
        except KeyError:
            continue
        kind = definition["type"]
        if kind == "boolean":
            if not isinstance(value, bool):
                violations.append(_violation(path, "must be a boolean"))
        elif kind == "integer":
            if isinstance(value, bool) or not isinstance(value, int):
                violations.append(_violation(path, "must be an integer"))
            elif value < definition["minimum"]:
                violations.append(
                    _violation(path, f"must be at least {definition['minimum']}")
                )
        elif kind == "number":
            if not _is_number(value) or not math.isfinite(float(value)):
                violations.append(_violation(path, "must be a finite number"))
            else:
                numeric = float(value)
                if numeric < definition["minimum"] or numeric > definition["maximum"]:
                    violations.append(
                        _violation(
                            path,
                            f"must be between {definition['minimum']} and {definition['maximum']}",
                        )
                    )
        elif kind == "enum" and value not in definition["values"]:
            values_text = ", ".join(definition["values"])
            violations.append(_violation(path, f"must be one of: {values_text}"))
        elif kind == "object":
            if not isinstance(value, dict):
                violations.append(_violation(path, "must be an object"))
            else:
                expected_criteria = set(definition["properties"])
                actual_criteria = set(value)
                for unknown in sorted(actual_criteria - expected_criteria):
                    violations.append(_violation(f"{path}.{unknown}", "unknown ranking weight"))
                for missing in sorted(expected_criteria - actual_criteria):
                    violations.append(_violation(f"{path}.{missing}", "ranking weight is required"))
                total = 0.0
                for key in sorted(actual_criteria & expected_criteria):
                    weight = value[key]
                    if not _is_number(weight) or not math.isfinite(float(weight)):
                        violations.append(_violation(f"{path}.{key}", "must be a finite number"))
                    elif float(weight) < 0.0 or float(weight) > 1.0:
                        violations.append(_violation(f"{path}.{key}", "must be between 0 and 1"))
                    else:
                        total += float(weight)
                if expected_criteria.issubset(actual_criteria) and not math.isclose(
                    total, 1.0, rel_tol=0.0, abs_tol=1e-6
                ):
                    violations.append(_violation(path, "ranking weights must sum to 1"))

    if violations:
        raise DiscoveryPreferencesValidationError(
            "Discovery Launch preferences failed validation", violations
        )

    # JSON has no separate integer/float distinction for settings consumers.  Keep the
    # declared integer fields as integers and normalize all accepted numeric weights and
    # sampling values to floats for deterministic snapshots.
    normalized_values = copy.deepcopy(values)
    for path, definition in _PARAMETER_DEFINITIONS.items():
        if definition["type"] != "number":
            continue
        parent: Any = normalized_values
        parts = path.split(".")
        for part in parts[:-1]:
            parent = parent[part]
        parent[parts[-1]] = float(parent[parts[-1]])
    criteria = normalized_values["agents"]["ranking"]["criteria"]
    for key in criteria:
        criteria[key] = float(criteria[key])
    return normalized_values


class DiscoveryLaunchPreferences:
    """Own validated global Discovery Launch defaults and their atomic storage."""

    schema_version = 1

    def __init__(self, path: str | Path):
        self.path = Path(path)
        self._values = copy.deepcopy(DEFAULT_DISCOVERY_LAUNCH_PREFERENCES)
        self._load()

    def _load(self) -> None:
        try:
            payload = json.loads(self.path.read_text(encoding="utf-8"))
        except (FileNotFoundError, OSError, json.JSONDecodeError):
            return
        if not isinstance(payload, dict):
            return
        stored_version = payload.get("schema_version")
        if stored_version is not None and stored_version != self.schema_version:
            return
        values = payload.get("values", payload)
        # Backend was added as a top-level setting.  Preserve older valid settings
        # files by applying the installed default only when the field is absent;
        # Removed backend identities are intentionally rejected by the normal
        # closed-enum validation below.
        if isinstance(values, dict) and "backend" not in values:
            values = {"backend": DEFAULT_DISCOVERY_LAUNCH_PREFERENCES["backend"], **values}
        try:
            self._values = _validate_shape_and_values(values)
        except DiscoveryPreferencesValidationError:
            # A damaged or stale developer-owned file must not make the sidecar unusable.
            # The installed defaults are authoritative until a valid save replaces it.
            self._values = copy.deepcopy(DEFAULT_DISCOVERY_LAUNCH_PREFERENCES)

    def get(self) -> dict[str, Any]:
        return copy.deepcopy(self._values)

    def snapshot(self) -> dict[str, Any]:
        """Return the immutable-by-convention values copied into a new Launch."""
        values = self.get()
        # ``launch_discovery.py`` deliberately collapses a skipped idea-generation
        # execution to one round.  Record that effective value in the Launch snapshot
        # so the persisted configuration describes what the runner will actually do.
        if values["skip_idea_generation"]:
            values["workflow"]["loop_rounds"] = 1
        return values

    def save(self, proposed: Mapping[str, Any]) -> dict[str, Any]:
        """Validate and atomically replace the complete defaults document.

        The endpoint accepts either the complete values object or a ``values`` wrapper.
        A wrapper is useful for the settings document; omitted fields are filled from the
        current defaults, but every supplied field is still validated and unknown fields
        are rejected.  The ranking criteria object remains all-or-nothing.
        """
        if not isinstance(proposed, Mapping):
            raise DiscoveryPreferencesValidationError(
                "Discovery Launch preferences must be an object",
                [_violation("", "an object is required")],
            )
        wrapper_unknown = set(proposed) - {
            "values",
            "schema_version",
            "defaults",
            "parameters",
        }
        if "values" in proposed:
            wrapper_violations = [
                _violation(key, "unknown settings document field")
                for key in sorted(wrapper_unknown)
            ]
            if wrapper_violations:
                raise DiscoveryPreferencesValidationError(
                    "Discovery Launch preferences contain unknown fields",
                    wrapper_violations,
                )
            supplied_version = proposed.get("schema_version")
            if supplied_version is not None and supplied_version != self.schema_version:
                raise DiscoveryPreferencesValidationError(
                    "Discovery Launch preferences use an unsupported schema version",
                    [_violation("schema_version", "must match the installed schema version")],
                )
        candidate_payload: Any = proposed.get("values", proposed)
        if not isinstance(candidate_payload, Mapping):
            raise DiscoveryPreferencesValidationError(
                "Discovery Launch preferences values must be an object",
                [_violation("values", "an object is required")],
            )
        unknown_top = set(candidate_payload) - set(_EXPECTED_SHAPE)
        for key in sorted(unknown_top):
            # Validate the full candidate below so callers receive all violations at once.
            pass
        candidate = copy.deepcopy(self._values)
        _deep_merge(candidate, candidate_payload)
        normalized = _validate_shape_and_values(candidate)
        self._atomic_write(normalized)
        self._values = normalized
        return self.document()

    def document(self) -> dict[str, Any]:
        values = self.get()
        defaults = copy.deepcopy(DEFAULT_DISCOVERY_LAUNCH_PREFERENCES)
        parameters = copy.deepcopy(_PARAMETER_DEFINITIONS)
        return {
            "schema_version": self.schema_version,
            "values": values,
            "defaults": defaults,
            "parameters": parameters,
        }

    def _atomic_write(self, values: dict[str, Any]) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        descriptor, temporary_name = tempfile.mkstemp(
            prefix=f".{self.path.name}.", suffix=".tmp", dir=self.path.parent
        )
        temporary_path = Path(temporary_name)
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
                json.dump(
                    {"schema_version": self.schema_version, "values": values},
                    handle,
                    ensure_ascii=False,
                    indent=2,
                    sort_keys=True,
                )
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary_path, self.path)
        finally:
            temporary_path.unlink(missing_ok=True)


def _deep_merge(target: dict[str, Any], patch: Mapping[str, Any]) -> None:
    """Merge a settings patch while retaining omitted sibling defaults."""
    for key, value in patch.items():
        if isinstance(value, Mapping) and isinstance(target.get(key), dict):
            _deep_merge(target[key], value)
        else:
            target[key] = copy.deepcopy(value)


def discovery_preferences_document(path: str | Path) -> dict[str, Any]:
    """Convenience adapter for callers that only have a storage path."""
    return DiscoveryLaunchPreferences(path).document()


