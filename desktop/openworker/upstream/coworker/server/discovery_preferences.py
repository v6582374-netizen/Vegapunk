class DiscoveryPreferencesValidationError(ValueError):
    """Raised when a proposed Discovery Launch preference set is invalid."""

    def __init__(self, message: str, violations: list[dict[str, Any]] | None = None):
        super().__init__(message)
        self.violations = violations or []

    def to_dict(self) -> dict[str, Any]:
        result: dict[str, Any] = {"message": str(self)}
        if self.violations:
            result["violations"] = copy.deepcopy(self.violations)
        return result


